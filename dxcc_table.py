# Ordina per lunghezza prefisso decrescente: i prefissi più specifici prima
_DXCC_SORTED = sorted(DXCC_PREFIXES, key=lambda e: -len(e[0]))


def lookup_dxcc(callsign: str):
    """Ritorna (lat, lng, country) per un nominativo, o None.
    Cerca il prefisso più lungo che corrisponde all'inizio del nominativo,
    considerando anche eventuali prefissi con barra (3A/IK1XYZ)."""
    call = (callsign or "").strip().upper()
    if not call:
        return None
    # nomi come "3A/IK1XYZ": prova anche il prefisso prima della barra
    candidates = [call]
    if "/" in call:
        candidates = call.split("/") + [call]
    for cand in candidates:
        for prefix, lat, lng, country in _DXCC_SORTED:
            if cand.startswith(prefix):
                return lat, lng, country
    return None
